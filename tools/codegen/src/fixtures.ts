import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Kinds, Messages, type KindName, type MessageName } from '../../../node/packages/protocol/src/generated/core.ts';
import { writeHeader } from '../../../node/packages/protocol/src/wire/envelope.ts';
import { WireWriter } from '../../../node/packages/protocol/src/wire/writer.ts';
import { cases, type FixtureCase } from './fixture-cases.ts';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
/** Golden fixture file read by the TypeScript and Java test suites. */
export const FIXTURE_FILE = join(root, 'fixtures/wire.tsv');

const hex = (b: Uint8Array) => Buffer.from(b).toString('hex');

/** Encodes one fixture case with the TypeScript codecs. */
export function encodeCase(c: FixtureCase): Uint8Array {
  const w = new WireWriter();
  if (c.space === 'envelope') writeHeader(w, c.header);
  else if (c.space === 'message') Messages[c.name as MessageName].codec.write(w, c.value as never);
  else Kinds[c.name as KindName].codec.write(w, c.value as never);
  return w.toBytes();
}

/** Tab-separated lines: space, name, label, hex. Envelope lines use `-` as the name. */
export function renderFixtures(): string {
  const lines = ['# GENERATED by `pnpm fixtures` from tools/codegen/src/fixture-cases.ts. space\tname\tlabel\thex'];
  for (const c of cases) {
    const name = c.space === 'envelope' ? '-' : c.name;
    lines.push([c.space, name, c.label, hex(encodeCase(c))].join('\t'));
  }
  return lines.join('\n') + '\n';
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const content = renderFixtures();
  if (process.argv.includes('--check')) {
    if (readFileSync(FIXTURE_FILE, 'utf8') !== content) {
      console.error('fixtures/wire.tsv is out of date. Run `pnpm fixtures`.');
      process.exit(1);
    }
    console.log('Fixtures are up to date.');
  } else {
    writeFileSync(FIXTURE_FILE, content);
    console.log(`Wrote ${cases.length} fixtures.`);
  }
}
