import { isMap, parseDocument, type Document } from 'yaml';

export type PrimName = 'bool' | 'i32' | 'u32' | 'i64' | 'u64' | 'f32' | 'f64' | 'string' | 'bytes' | 'any';
export type ArrayElem = 'f64' | 'f32' | 'i32' | 'u16';

export type TypeRef =
  | { t: 'prim'; name: PrimName }
  | { t: 'array'; elem: ArrayElem }
  | { t: 'list'; of: TypeRef }
  | { t: 'map'; of: TypeRef }
  | { t: 'enum'; name: string }
  | { t: 'struct'; name: string }
  | { t: 'union'; name: string };

export interface Field {
  name: string;
  type: TypeRef;
  optional: boolean;
  /** Raw default literal from the schema, if any. */
  default?: string;
  /** Trailing `#` comment on the field's schema line, if any. */
  doc?: string;
}

export interface StructDef {
  /** Schema name (`Vec3d`, `auth.challenge`, `core:box`). */
  schemaName: string;
  /** Generated type name. */
  typeName: string;
  fields: Field[];
  /** Trailing `#` comment on the type's schema line, if any. */
  doc?: string;
}

export interface EnumDef {
  name: string;
  values: string[];
}

export interface UnionDef {
  name: string;
  variants: { key: string; struct: string }[];
}

export type DeliveryName = 'control' | 'reliable' | 'latest' | 'unreliable';

export interface MessageDef extends StructDef {
  id: number;
  from: 'node' | 'mod' | 'both';
  delivery: DeliveryName;
  response?: string;
  timeoutMs?: number;
  constName: string;
}

export interface KindDef extends StructDef {
  id: number;
  constName: string;
}

export interface Schema {
  namespace: string;
  /** Set for an extension schema: its id, Java package, and the core schema its types may use. */
  extension?: { id: string; java: string; base: Schema };
  protocol: { major: number; minor: number };
  enums: EnumDef[];
  structs: StructDef[];
  unions: UnionDef[];
  kinds: KindDef[];
  messages: MessageDef[];
}

const PRIMS = new Set<string>(['bool', 'i32', 'u32', 'i64', 'u64', 'f32', 'f64', 'string', 'bytes', 'any']);
const ARRAY_ELEMS = new Set<string>(['f64', 'f32', 'i32', 'u16']);
/** Names that would shadow java.lang types or read badly; such message types get a `Message` suffix. */
const RESERVED_TYPE_NAMES = new Set(['Error', 'Object', 'String', 'Record', 'Override', 'Class', 'Enum', 'Exception', 'Void', 'Integer', 'Long']);

/** PascalCase of a schema name: `auth.challenge` gives `AuthChallenge`. */
export function pascal(name: string): string {
  return name
    .split(/[.:\-_]/)
    .filter(Boolean)
    .map((p) => p[0]!.toUpperCase() + p.slice(1))
    .join('');
}

/** CONSTANT_CASE of a schema name without its namespace: `core:hud.bar` gives `HUD_BAR`. */
export function constCase(name: string): string {
  return name
    .replace(/^[a-z0-9]+:/, '')
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .split(/[.:\-_]/)
    .filter(Boolean)
    .map((p) => p.toUpperCase())
    .join('_');
}

/** First line of every generated file. */
export const GENERATED_HEADER = '// GENERATED by tools/codegen from schema/core.yaml. Do not edit; run `pnpm gen`.\n';

/** The generated-file header naming the schema it came from. */
export function header(schema: Schema): string {
  if (schema.extension === undefined) return GENERATED_HEADER;
  return `// GENERATED by tools/codegen from schema/ext/${schema.extension.id.replace(':', '-')}.yaml. Do not edit; run \`pnpm gen\`.\n`;
}

/** Names of core enums, structs and unions an extension schema uses, sorted. */
export function externalTypes(schema: Schema): string[] {
  const base = schema.extension?.base;
  if (base === undefined) return [];
  const coreNames = new Set([...base.enums.map((e) => e.name), ...base.structs.map((x) => x.typeName), ...base.unions.map((u) => u.name)]);
  const used = new Set<string>();
  const visit = (t: TypeRef): void => {
    if (t.t === 'list' || t.t === 'map') visit(t.of);
    else if ((t.t === 'struct' || t.t === 'enum' || t.t === 'union') && coreNames.has(t.name)) used.add(t.name);
  };
  for (const d of [...schema.structs, ...schema.kinds, ...schema.messages]) for (const f of d.fields) visit(f.type);
  return [...used].sort();
}

/** Wire id as written in generated code and docs, e.g. `0x0a`. */
export function hexId(id: number): string {
  return `0x${id.toString(16).padStart(2, '0')}`;
}

/**
 * One-sentence summary for the doc comment of a generated struct, kind or message type.
 * `code` formats a schema name for the target language's doc syntax.
 */
export function typeSummary(def: StructDef | KindDef | MessageDef, code: (name: string) => string): string {
  if ('from' in def) {
    const sender = def.from === 'both' ? 'either side' : def.from;
    const text = `Payload of message ${code(def.schemaName)} (id ${hexId(def.id)}), sent by ${sender} with ${def.delivery} delivery.`;
    if (!def.response) return text;
    const timeout = def.timeoutMs === undefined ? '' : `; default timeout ${def.timeoutMs} ms`;
    return `${text} Answered by ${code(def.response)}${timeout}.`;
  }
  if ('id' in def) return `Data of object kind ${code(def.schemaName)} (id ${def.id}).`;
  return def.doc ? `Struct ${code(def.schemaName)}: ${def.doc}.` : `Struct ${code(def.schemaName)}.`;
}

/** Doc text for one field: its schema comment and default, or undefined when it has neither. */
export function fieldDoc(f: Field, code: (literal: string) => string): string | undefined {
  const parts: string[] = [];
  if (f.doc) parts.push(`${sentence(f.doc)}.`);
  if (f.default !== undefined) parts.push(`Default ${code(f.default.replace(/^['"]|['"]$/g, ''))}.`);
  return parts.length > 0 ? parts.join(' ') : undefined;
}

/**
 * Turns a schema comment into sentence form. A value list (`a | b | c`) gets a `One of:` prefix;
 * otherwise a leading lowercase word is capitalised, but never an identifier or a coordinate name.
 */
function sentence(comment: string): string {
  if (/^[^\s|,]+ \| /.test(comment)) return `One of: ${comment}`;
  return /^[a-z]{2,}(?=[\s,]|$)/.test(comment) ? comment[0]!.toUpperCase() + comment.slice(1) : comment;
}

/** Reads trailing line comments of types and fields; keys are `type` and `type.field`. */
function schemaComments(document: Document): Map<string, string> {
  const out = new Map<string, string>();
  const add = (key: string, comment: string | null | undefined) => {
    const text = comment?.trim();
    if (text) out.set(key, text);
  };
  const addFields = (type: string, fields: unknown) => {
    if (!isMap(fields)) return;
    for (const f of fields.items) add(`${type}.${String((f.key as { value: unknown }).value)}`, (f.value as { comment?: string | null } | null)?.comment);
  };
  for (const section of ['structs', 'kinds', 'messages']) {
    const types = document.get(section, true);
    if (!isMap(types)) continue;
    for (const t of types.items) {
      const name = String((t.key as { value: unknown }).value);
      if (section === 'structs') {
        if (isMap(t.value) && t.value.flow) add(name, t.value.comment);
        addFields(name, t.value);
      } else if (isMap(t.value)) {
        addFields(name, t.value.get('fields', true));
      }
    }
  }
  return out;
}

/** Parses and validates schema text. Throws on unknown types, invalid defaults and duplicate or out-of-range ids. */
export function parseSchema(source: string, base?: Schema): Schema {
  const document = parseDocument(source);
  if (document.errors.length > 0) throw document.errors[0];
  const doc = document.toJS() as Record<string, any>;
  const comments = schemaComments(document);
  const enumNames = new Set([...Object.keys(doc.enums ?? {}), ...(base?.enums.map((e) => e.name) ?? [])]);
  const structNames = new Set([...Object.keys(doc.structs ?? {}), ...(base?.structs.map((x) => x.typeName) ?? [])]);
  const unionNames = new Set([...Object.keys(doc.unions ?? {}), ...(base?.unions.map((u) => u.name) ?? [])]);

  const parseType = (expr: string, where: string): TypeRef => {
    const e = expr.trim();
    const list = /^list<(.+)>$/.exec(e);
    if (list) return { t: 'list', of: parseType(list[1]!, where) };
    const map = /^map<\s*string\s*,\s*(.+)>$/.exec(e);
    if (map) return { t: 'map', of: parseType(map[1]!, where) };
    const arr = /^([a-z0-9]+)\[\]$/.exec(e);
    if (arr) {
      if (!ARRAY_ELEMS.has(arr[1]!)) throw new Error(`${where}: unsupported packed array element ${arr[1]}`);
      return { t: 'array', elem: arr[1] as ArrayElem };
    }
    if (PRIMS.has(e)) return { t: 'prim', name: e as PrimName };
    if (enumNames.has(e)) return { t: 'enum', name: e };
    if (structNames.has(e)) return { t: 'struct', name: e };
    if (unionNames.has(e)) return { t: 'union', name: e };
    throw new Error(`${where}: unknown type '${e}'`);
  };

  const parseFields = (raw: Record<string, unknown> | undefined, where: string): Field[] => {
    const out: Field[] = [];
    for (const [name, spec] of Object.entries(raw ?? {})) {
      const text = String(spec);
      const [typePart, defaultPart] = text.split(/\s=\s/, 2) as [string, string | undefined];
      const optional = typePart.trim().endsWith('?');
      const type = parseType(optional ? typePart.trim().slice(0, -1) : typePart, `${where}.${name}`);
      if (optional && defaultPart !== undefined) throw new Error(`${where}.${name}: optional fields cannot have defaults`);
      const field: Field = { name, type, optional };
      if (defaultPart !== undefined) field.default = defaultPart.trim();
      const comment = comments.get(`${where}.${name}`);
      if (comment !== undefined) field.doc = comment;
      out.push(field);
    }
    return out;
  };

  const enums: EnumDef[] = Object.entries(doc.enums ?? {}).map(([name, values]) => ({ name, values: values as string[] }));
  const structs: StructDef[] = Object.entries(doc.structs ?? {}).map(([name, fields]) => {
    const s: StructDef = { schemaName: name, typeName: name, fields: parseFields(fields as Record<string, unknown>, name) };
    const comment = comments.get(name);
    if (comment !== undefined) s.doc = comment;
    return s;
  });
  const unions: UnionDef[] = Object.entries(doc.unions ?? {}).map(([name, variants]) => ({
    name,
    variants: Object.entries(variants as Record<string, string>).map(([key, struct]) => {
      if (!structNames.has(struct)) throw new Error(`${name}.${key}: union variants must be structs`);
      return { key, struct };
    }),
  }));
  const kinds: KindDef[] = Object.entries(doc.kinds ?? {}).map(([name, def]) => {
    const d = def as { id?: number; fields?: Record<string, unknown> };
    return {
      schemaName: name,
      typeName: `${pascal(name.replace(/^[a-z0-9]+:/, ''))}Data`,
      constName: constCase(name),
      id: d.id ?? 0,
      fields: parseFields(d.fields, name),
    };
  });
  const messages: MessageDef[] = Object.entries(doc.messages ?? {}).map(([name, def]) => {
    const d = def as Record<string, any>;
    let typeName = pascal(name);
    if (RESERVED_TYPE_NAMES.has(typeName) || structNames.has(typeName) || unionNames.has(typeName) || enumNames.has(typeName)) typeName += 'Message';
    const m: MessageDef = {
      schemaName: name,
      typeName,
      constName: constCase(name),
      id: d.id ?? 0,
      from: d.from,
      delivery: d.delivery,
      fields: parseFields(d.fields, name),
    };
    if (d.response !== undefined) m.response = d.response;
    if (d.timeoutMs !== undefined) m.timeoutMs = d.timeoutMs;
    return m;
  });

  const schema: Schema = { namespace: doc.namespace, protocol: doc.protocol, enums, structs, unions, kinds, messages };
  if (base === undefined) {
    validate(messages, kinds);
    return schema;
  }
  validateExtension(doc, messages, kinds, enums, structs, unions);
  schema.extension = { id: `${doc.namespace}:${doc.extension}`, java: doc.java, base };
  return schema;
}

/**
 * Extension schemas: every kind and message is named under the extension's namespace, ids are left to
 * the mod (assigned per connection in `welcome`), and own type names must not shadow core ones.
 */
function validateExtension(doc: Record<string, any>, messages: MessageDef[], kinds: KindDef[], enums: EnumDef[], structs: StructDef[], unions: UnionDef[]): void {
  if (typeof doc.namespace !== 'string' || typeof doc.extension !== 'string' || typeof doc.java !== 'string') {
    throw new Error('extension schemas need namespace, extension and java');
  }
  for (const x of [...messages, ...kinds]) {
    if (!x.schemaName.startsWith(`${doc.namespace}:`)) throw new Error(`${x.schemaName}: extension names start with ${doc.namespace}:`);
    if (x.id !== 0) throw new Error(`${x.schemaName}: extension ids are assigned by the mod; leave id out`);
  }
  for (const m of messages) {
    if (m.response && !messages.some((x) => x.schemaName === m.response)) throw new Error(`${m.schemaName}: unknown response ${m.response}`);
  }
  const own = [...enums.map((e) => e.name), ...structs.map((x) => x.typeName), ...unions.map((u) => u.name)];
  if (new Set(own).size !== own.length) throw new Error('duplicate type name in extension schema');
}

function validate(messages: MessageDef[], kinds: KindDef[]): void {
  const seen = new Map<number, string>();
  for (const m of messages) {
    if (m.id >= 0x100) throw new Error(`${m.schemaName}: core message ids must be below 0x100`);
    const prior = seen.get(m.id);
    if (prior) throw new Error(`duplicate message id 0x${m.id.toString(16)}: ${prior}, ${m.schemaName}`);
    seen.set(m.id, m.schemaName);
    if (m.response && !messages.some((x) => x.schemaName === m.response)) throw new Error(`${m.schemaName}: unknown response ${m.response}`);
  }
  const kindIds = new Map<number, string>();
  for (const k of kinds) {
    if (k.id < 1 || k.id >= 0x100) throw new Error(`${k.schemaName}: core kind ids must be in 1..255`);
    const prior = kindIds.get(k.id);
    if (prior) throw new Error(`duplicate kind id ${k.id}: ${prior}, ${k.schemaName}`);
    kindIds.set(k.id, k.schemaName);
  }
}

/** Index after which every field is optional or defaulted; decoders reject shorter arrays. */
export function requiredCount(fields: Field[]): number {
  let n = 0;
  fields.forEach((f, i) => {
    if (!f.optional && f.default === undefined) n = i + 1;
  });
  return n;
}
